    def cache_css(self, organization_id: str, css: str) -> None:
        """Cache CSS for organization."""
        cache.set(f'{self.cache_prefix}css_{organization_id}', css, 3600)  # 1 hour TTL
    
    def clear_css_cache(self, organization_id: str) -> None:
        """Clear cached CSS for organization."""
        cache.delete(f'{self.cache_prefix}css_{organization_id}')
    
