    def validate_logo(self, file_data: bytes, filename: str) -> Tuple[bool, str]:
        """
        Validate logo file.
        
        Args:
            file_data: File data as bytes
            filename: Original filename
        
        Returns:
            Tuple of (is_valid, message)
        """
        # Check file size (max 5MB)
        if len(file_data) > 5 * 1024 * 1024:
            return False, "Logo file size exceeds 5MB limit"
        
        # Check file type
        ext = filename.split('.')[-1].lower()
        allowed_types = ['png', 'jpg', 'jpeg', 'svg', 'gif', 'webp']
        if ext not in allowed_types:
            return False, f"Unsupported file type: {ext}. Allowed: {', '.join(allowed_types)}"
        
        # Check dimensions for raster images
        if ext in ['png', 'jpg', 'jpeg', 'gif', 'webp']:
            try:
                from PIL import Image
                import io
                img = Image.open(io.BytesIO(file_data))
                width, height = img.size
                
                if width > 1200 or height > 600:
                    return False, f"Logo dimensions ({width}x{height}) exceed maximum (1200x600)"
                if width < 100 or height < 40:
                    return False, f"Logo dimensions ({width}x{height}) below minimum (100x40)"
                
                # Check aspect ratio
                ratio = width / height
                if ratio < 1.5 or ratio > 4.0:
                    return False, f"Logo aspect ratio ({ratio:.2f}) should be between 1.5 and 4.0"
                
            except ImportError:
                # PIL not available, skip dimension validation
                pass
            except Exception as e:
                pass
        
        return True, "Logo validated successfully"
    
